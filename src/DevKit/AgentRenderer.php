<?php

declare(strict_types=1);

namespace DropContext\DevKit;

use Symfony\Component\Yaml\Yaml;

/**
 * Renders the drop-context-dev agent for clients that cannot read Claude
 * Code's agent format, and the OpenCode commands that run the skills.
 *
 * Every rendered file carries MARKER, which is how dev:install recognizes
 * a file it wrote and may overwrite or remove.
 */
class AgentRenderer {

  public const MARKER = 'Generated by drop-context dev:install';

  /** Cursor subagent: Markdown with name, description and model. */
  public function cursor(DevKit $kit): string {
    $agent = $kit->agent();
    return $this->markdown($kit, [
      'name' => $agent['name'],
      'description' => $agent['description'],
      'model' => 'inherit',
    ], $agent['body']);
  }

  /**
   * OpenCode agent: usable as a primary agent and as a subagent.
   *
   * Mirrors Claude Code's tool list: no web or subagent tools, and the
   * read-only drop-context MCP tools allowed without a prompt.
   */
  public function opencode(DevKit $kit): string {
    $agent = $kit->agent();
    return $this->markdown($kit, [
      'description' => $agent['description'],
      'mode' => 'all',
      'permission' => [
        'webfetch' => 'deny',
        'websearch' => 'deny',
        'task' => 'deny',
        DevKitInstaller::MCP_SERVER . '_*' => 'allow',
      ],
    ], $agent['body']);
  }

  /** Codex custom agent (TOML). */
  public function codex(DevKit $kit): string {
    $agent = $kit->agent();
    if (str_contains($agent['body'], "'''")) {
      throw new \RuntimeException(DevKit::AGENT_FILE . " contains ''' and cannot become a Codex agent.");
    }
    $flags = JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE;
    // A JSON string literal is a valid TOML basic string.
    return '# ' . $this->notice($kit) . "\n"
      . 'name = ' . json_encode($agent['name'], $flags) . "\n"
      . 'description = ' . json_encode($agent['description'], $flags) . "\n"
      . "developer_instructions = '''\n"
      . rtrim($agent['body'], "\n") . "\n"
      . "'''\n";
  }

  /**
   * OpenCode command that loads a skill.
   *
   * A skill that forks into an agent in Claude Code (`context: fork` +
   * `agent:`) runs as a subtask of that agent here.
   */
  public function opencodeCommand(DevKit $kit, string $skill): string {
    $meta = $kit->skillFrontmatter($skill);
    $frontmatter = ['description' => self::summary((string) ($meta['description'] ?? $skill))];
    if (($meta['context'] ?? null) === 'fork' && is_string($meta['agent'] ?? null)) {
      $frontmatter['agent'] = $meta['agent'];
      $frontmatter['subtask'] = TRUE;
    }
    $body = "Load the `{$skill}` skill with the skill tool and follow it exactly.\n\n"
      . "Request: \$ARGUMENTS\n";
    return $this->markdown($kit, $frontmatter, $body);
  }

  /** The first clause of a skill description, for a command list. */
  public static function summary(string $description): string {
    $text = trim(preg_replace('/\s+/', ' ', $description) ?? $description);
    $cut = preg_split('/[:.](\s|$)/', $text, 2);
    return trim($cut[0] ?? $text);
  }

  /** @param array<string, mixed> $frontmatter */
  private function markdown(DevKit $kit, array $frontmatter, string $body): string {
    return "---\n# " . $this->notice($kit) . "\n"
      . Yaml::dump($frontmatter, 4, 2)
      . "---\n\n"
      . rtrim($body, "\n") . "\n";
  }

  private function notice(DevKit $kit): string {
    return self::MARKER . ' from drop-context-dev ' . $kit->version() . '. Run it again to update.';
  }

}
